import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const db=new PGlite();
await db.exec('CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;');
await db.exec(await readFile(new URL('../supabase/001_loot_manager.sql',import.meta.url),'utf8'));
const alice={id:'alice',email:'alice@example.com',name:'Alice'},bob={id:'bob',email:'bob@example.com',name:'Bob'},carol={id:'carol',email:'carol@example.com',name:'Carol'};
const alpha='00000000-0000-4000-8000-000000000001',beta='00000000-0000-4000-8000-000000000002';
const blank={members:[],runs:[],sales:[],vendingPrices:{},lootImages:{},payoutQueue:[],auditLog:[]};
await db.exec('SET ROLE service_role;');
async function op(name,user,guild,data={}){
  const {rows}=await db.query('SELECT public.loot_manager_operation($1,$2::jsonb,$3::uuid,$4::jsonb) AS result',[name,user?JSON.stringify(user):null,guild??null,JSON.stringify(data)]);
  return rows[0].result;
}
for(const user of [alice,bob,carol])await op('account',user);
assert.equal((await op('guild_list'))._error.status,401);
await op('guild_create',alice,null,{id:alpha,name:'Alpha',slug:'alpha',isPublic:true,state:blank});
await op('guild_create',bob,null,{id:beta,name:'Beta',slug:'beta',isPublic:false,state:blank});
assert.equal((await op('guild_context',bob,alpha))._error.status,403);
assert.equal((await op('ledger_get',bob,alpha))._error.status,403);
assert.equal((await op('public_ledger',null,beta))._error.status,404);
const saved={...blank,members:[{id:'m1',name:'Alpha player',active:true}]};
assert.equal((await op('ledger_save',alice,alpha,{version:0,state:saved})).version,1);
assert.equal((await op('ledger_save',alice,alpha,{version:0,state:blank}))._error.status,409);
assert.equal((await op('ledger_get',bob,beta)).state.members.length,0);
assert.equal((await op('public_ledger',null,alpha)).state.members[0].name,'Alpha player');
assert.equal((await op('public_list')).length,1);
const duplicate=await op('guild_create',alice,null,{id:'00000000-0000-4000-8000-000000000003',name:'Duplicate',slug:'alpha',isPublic:false,state:blank});
assert.equal(duplicate._error.status,409);assert.equal((await op('guild_list',alice)).length,1);
const inviteId='00000000-0000-4000-8000-000000000004';
await op('invite_create',alice,alpha,{id:inviteId,email:carol.email,role:'manager',tokenHash:'token',expiresAt:new Date(Date.now()+86400000).toISOString()});
assert.equal((await op('invite_accept',bob,null,{tokenHash:'token'}))._error.status,403);
assert.equal((await op('invite_accept',carol,null,{tokenHash:'token'})).guildId,alpha);
assert.equal((await op('invite_accept',carol,null,{tokenHash:'token'}))._error.status,403);
assert.equal((await op('guild_context',carol,alpha)).role,'manager');
assert.equal((await op('settings_update',carol,alpha,{name:'Changed',description:'',isPublic:true}))._error.status,403);
assert.equal((await op('settings_get',carol,alpha)).invites.length,0);
assert.equal((await op('team_remove',alice,alpha,{userId:'alice'}))._error.status,403);
await op('team_remove',alice,alpha,{userId:'carol'});
assert.equal((await op('ledger_save',carol,alpha,{version:1,state:blank}))._error.status,403);
await op('settings_update',alice,alpha,{name:'Alpha',description:'',isPublic:false});
assert.equal((await op('public_ledger',null,alpha))._error.status,404);
await db.exec('RESET ROLE; SET ROLE anon;');

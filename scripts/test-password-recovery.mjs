import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const input=await readFile(new URL('../lib/password-recovery.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(input,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {createRecoveryGrant,verifyRecoveryGrant,recoverySeconds}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const secret='isolated-test-signing-key',time=1_800_000_000_000;
const grant=await createRecoveryGrant(secret,'user-a','recovery-session-a',time);
assert.equal(await verifyRecoveryGrant(grant,secret,'user-a','recovery-session-a',time+1000),true);
assert.equal(await verifyRecoveryGrant(undefined,secret,'user-a','recovery-session-a',time),false);
assert.equal(await verifyRecoveryGrant(grant,secret,'user-b','recovery-session-a',time),false);
assert.equal(await verifyRecoveryGrant(grant,secret,'user-a','ordinary-sign-in-session',time),false);
assert.equal(await verifyRecoveryGrant(grant,'different-key','user-a','recovery-session-a',time),false);
assert.equal(await verifyRecoveryGrant(grant,secret,'user-a','recovery-session-a',time+recoverySeconds*1000),false);
assert.equal(await verifyRecoveryGrant(grant,secret,'user-a','recovery-session-a',time-1000),false);
assert.equal(await verifyRecoveryGrant(grant+'.extra',secret,'user-a','recovery-session-a',time),false);
const [payload,signature]=grant.split('.');const altered=Buffer.from(JSON.stringify({userId:'user-b',session:'fake',expires:time+recoverySeconds*1000})).toString('base64url');
assert.equal(await verifyRecoveryGrant(altered+'.'+signature,secret,'user-b','fake',time),false);
assert.equal(await verifyRecoveryGrant(payload+'.invalid',secret,'user-a','recovery-session-a',time),false);
console.log('Recovery grants reject missing proof, tampering, expiry, and other users or sessions.');
